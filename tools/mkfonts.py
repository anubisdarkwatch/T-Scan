#!/usr/bin/env python3
"""Generate TFT_eSPI smooth fonts (VLW, as C arrays) + an alpha-mask icon
from the Anubis Darkwatch brand fonts.  Usage: mkfonts.py <fontsdir> <out.h>"""
import struct, sys
from PIL import Image, ImageDraw, ImageFont

FD = sys.argv[1]
ORB = f"{FD}/fontsource-orbitron-5.3.0/files/orbitron-latin-900-normal.woff"
STM = f"{FD}/fontsource-share-tech-mono-5.3.0/files/share-tech-mono-latin-400-normal.woff"
HIE = f"{FD}/fontsource-noto-sans-egyptian-hieroglyphs-5.3.0/files/noto-sans-egyptian-hieroglyphs-egyptian-hieroglyphs-400-normal.woff"

def vlw(path, px, chars):
    f = ImageFont.truetype(path, px)
    asc, desc = f.getmetrics()
    glyphs, bitmaps = [], []
    for cp in chars:
        ch = chr(cp)
        adv = round(f.getlength(ch))
        l, t, r, b = f.getbbox(ch, anchor="ls")       # relative to baseline origin
        w, h = r - l, b - t
        if w <= 0 or h <= 0:                           # space etc: 1x1 blank
            glyphs.append((cp, 1, 1, max(adv, 1), 0, 0)); bitmaps.append(b"\0"); continue
        img = Image.new("L", (w, h), 0)
        ImageDraw.Draw(img).text((-l, -t), ch, font=f, fill=255, anchor="ls")
        glyphs.append((cp, h, w, adv, -t, l))          # dY = rows above baseline
        bitmaps.append(img.tobytes())
    out = struct.pack(">6i", len(glyphs), 11, px, 0, asc, desc)
    for g in glyphs: out += struct.pack(">7i", *g, 0)
    return out + b"".join(bitmaps)

def icon(path, px, cp):
    f = ImageFont.truetype(path, px)
    l, t, r, b = f.getbbox(chr(cp))
    img = Image.new("L", (r - l, b - t), 0)
    ImageDraw.Draw(img).text((-l, -t), chr(cp), font=f, fill=255)
    return img.size, img.tobytes()

def carr(name, data):
    rows = [", ".join(f"0x{x:02X}" for x in data[i:i + 24]) for i in range(0, len(data), 24)]
    return f"const uint8_t {name}[] PROGMEM = {{\n  " + ",\n  ".join(rows) + "\n};\n"

ascii_ = list(range(0x20, 0x7F))
latin1 = ascii_ + list(range(0xA1, 0x100))
out = ["// Generated by tools/mkfonts.py — Orbitron Black, Share Tech Mono (OFL), Noto Sans Egyptian Hieroglyphs (OFL)",
       "#pragma once", "#include <pgmspace.h>",
       "struct BrandFont { const uint8_t* data; uint8_t space; };", ""]
for name, path, px, cs in [("ORB_12", ORB, 12, ascii_), ("ORB_22", ORB, 22, ascii_), ("ORB_26", ORB, 26, ascii_),
                           ("STM_11", STM, 11, ascii_), ("STM_14", STM, 14, latin1)]:
    out.append(carr(name, vlw(path, px, cs)))
    sp = round(ImageFont.truetype(path, px).getlength(" "))
    out.append(f"static const BrandFont F_{name} = {{{name}, {sp}}};\n")
for name, px in [("JACKAL_S", 16), ("JACKAL_L", 52)]:
    (w, h), data = icon(HIE, px, 0x130E3)
    out.append(f"#define {name}_W {w}\n#define {name}_H {h}\n" + carr(name, data))
open(sys.argv[2], "w").write("\n".join(out))

# also dump PNG of the icon for a sanity look
(w, h), data = icon(HIE, 52, 0x130E3)
Image.frombytes("L", (w, h), data).save(sys.argv[2] + ".jackal.png")
